export type PixelName = keyof typeof PIXELS;

/** Build compact SVG rects (horizontal runs merged). */
export function pixelRects(name: PixelName): string {
  const rows = PIXELS[name];
  let out = '';
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      if (row[x] === '#' || row[x] === '&') {
        let w = 1;
        while (x + w < row.length && (row[x + w] === '#' || row[x + w] === '&')) w++;
        out += `<rect x="${x}" y="${y}" width="${w}" height="1"/>`;
        x += w;
      } else x++;
    }
  });
  return out;
}


