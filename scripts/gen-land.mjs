// Rasterises Natural Earth land polygons into a small text mask used by the ASCII globe.
import { feature } from 'topojson-client';
import { geoContains } from 'd3-geo';
import { readFileSync, writeFileSync } from 'node:fs';

const topo = JSON.parse(readFileSync('node_modules/world-atlas/land-110m.json', 'utf8'));
const land = feature(topo, topo.objects.land);
const W = 144, H = 72;
const rows = [];
for (let y = 0; y < H; y++) {
  let row = '';
  const lat = 90 - ((y + 0.5) * 180) / H;
  for (let x = 0; x < W; x++) {
    const lon = -180 + ((x + 0.5) * 360) / W;
    row += geoContains(land, [lon, lat]) ? '#' : '.';
  }
  rows.push(row);
}
writeFileSync('src/lib/landmask.ts', `// Generated by scripts/gen-land.mjs from Natural Earth (public domain). 144x72, equirectangular.\nexport const LAND_W = ${W};\nexport const LAND_H = ${H};\nexport const LAND: string[] = ${JSON.stringify(rows)};\n`);
console.log(rows.filter((_, i) => i % 3 === 0).map((r) => r.replace(/(.)./g, '$1')).join('\n'));
