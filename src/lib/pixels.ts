export type PixelName = keyof typeof PIXELS;

/** Build compact SVG rects (horizontal runs merged). */
export function pixelRects(name: PixelName): string {
  const rows = PIXELS[name];
  let out = '';
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      if (row[x] === '#' || row[x] === '&') {
        let w = 1;
        while (x + w < row.length && (row[x + w] === '#' || row[x + w] === '&')) w++;
        out += `<rect x="${x}" y="${y}" width="${w}" height="1"/>`;
        x += w;
      } else x++;
    }
  });
  return out;
}

export function drawPixel(ctx: CanvasRenderingContext2D, name: PixelName, x: number, y: number, size: number) {
  const rows = PIXELS[name];
  const p = size / 9;
  rows.forEach((row, ry) => {
    for (let rx = 0; rx < row.length; rx++) if (row[rx] !== '.') ctx.fillRect(Math.round(x + rx * p), Math.round(y + ry * p), Math.ceil(p), Math.ceil(p));
  });
}

